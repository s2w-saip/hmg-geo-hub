"""Extract the GA4/Visibility contract from the inspected Gold catalog, without data."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
REFERENCES = (
    "dim_region", "dim_country", "dim_engine", "dim_project", "dim_brand",
    "dim_category", "dim_source", "dim_owned_base", "dim_url",
)
GA4 = ("ga4_property", "ga4_value", "ga4_row", "ga4_users_window")
SEO = ("dim_crawl_bot", "page_visibility_daily", "page_crawl_daily", "page_seo_device_daily", "page_priority")
TABLES = {**dict.fromkeys(REFERENCES, "ref"), **dict.fromkeys(GA4 + SEO, "analytics"), "build": "ops"}
TYPES = {"int2": "smallint", "int4": "integer", "int8": "bigint", "bool": "boolean", "_text": "text[]"}
IDENTITIES = {
    "dim_region": "region_key", "dim_country": "geo_key", "dim_engine": "engine_key",
    "dim_project": "project_key", "dim_brand": "brand_key", "dim_category": "category_key",
    "dim_source": "source_key", "dim_owned_base": "owner_key", "dim_url": "url_key",
    "ga4_property": "prop_key", "dim_crawl_bot": "bot_key", "build": "build_id",
}
LINKS = (
    ("dim_country", "region_key", "dim_region", "region_key"),
    ("dim_project", "site_geo_key", "dim_country", "geo_key"),
    ("dim_source", "category_key", "dim_category", "category_key"),
    ("dim_source", "competitor_brand_key", "dim_brand", "brand_key"),
    ("dim_url", "source_key", "dim_source", "source_key"),
    ("dim_url", "owner_key", "dim_owned_base", "owner_key"),
    ("ga4_property", "geo_key", "dim_country", "geo_key"),
    ("ga4_value", "url_key", "dim_url", "url_key"),
    ("ga4_row", "prop_key", "ga4_property", "prop_key"),
    ("ga4_row", "engine_key", "dim_engine", "engine_key"),
    ("ga4_users_window", "prop_key", "ga4_property", "prop_key"),
    ("dim_crawl_bot", "engine_key", "dim_engine", "engine_key"),
    ("page_visibility_daily", "build_id", "build", "build_id"),
    ("page_visibility_daily", "project_key", "dim_project", "project_key"),
    ("page_visibility_daily", "url_key", "dim_url", "url_key"),
    ("page_visibility_daily", "geo_key", "dim_country", "geo_key"),
    ("page_crawl_daily", "build_id, project_key, url_key, date", "page_visibility_daily", "build_id, project_key, url_key, date"),
    ("page_crawl_daily", "bot_key", "dim_crawl_bot", "bot_key"),
    ("page_seo_device_daily", "build_id, project_key, url_key, date", "page_visibility_daily", "build_id, project_key, url_key, date"),
    ("page_priority", "build_id", "build", "build_id"),
    ("page_priority", "project_key", "dim_project", "project_key"),
    ("page_priority", "url_key", "dim_url", "url_key"),
)


def generate():
    source = json.loads((HERE / "gold-source-schema.json").read_text(encoding="utf-8"))
    lines = [
        "-- Generated by back/analytics/generate_schema.py; no source rows are copied.",
        "-- Source: Gold ERD 07_ga4.js / 08_vis.js and inspected PostgreSQL column/PK definitions.",
        "CREATE SCHEMA ref AUTHORIZATION hmg_analytics_owner;",
        "CREATE SCHEMA analytics AUTHORIZATION hmg_analytics_owner;",
        "CREATE SCHEMA ops AUTHORIZATION hmg_analytics_owner;",
    ]
    for table, schema in TABLES.items():
        columns = sorted((c for c in source["columns"] if c["table_name"] == table), key=lambda c: c["ordinal_position"])
        if not columns:
            raise ValueError(f"Missing inspected table: {table}")
        definitions = []
        for c in columns:
            column_type = TYPES.get(c["udt_name"], c["udt_name"])
            if c["udt_name"] == "numeric" and c["numeric_precision"]:
                column_type += f"({c['numeric_precision']},{c['numeric_scale']})"
            definition = f"    {c['column_name']} {column_type}"
            if c["column_name"] == IDENTITIES.get(table):
                definition += " GENERATED BY DEFAULT AS IDENTITY"
            if c["is_nullable"] == "NO":
                definition += " NOT NULL"
            definitions.append(definition)
        definitions.extend("    " + c["definition"] for c in source["constraints"] if c["table_name"] == table and c["contype"] in ("p", "u", "c"))
        lines.append(f"CREATE TABLE {schema}.{table} (\n" + ",\n".join(definitions) + "\n);")
    for i, (table, columns, target, target_columns) in enumerate(LINKS, 1):
        lines.append(f"ALTER TABLE {TABLES[table]}.{table} ADD CONSTRAINT ref_link_{i} FOREIGN KEY ({columns}) "
                     f"REFERENCES {TABLES[target]}.{target} ({target_columns}) DEFERRABLE INITIALLY DEFERRED;")
    # The discriminator is part of ga4_value's PK. A device key must never resolve to an event/page key.
    for table, kinds in (("ga4_row", ("channel", "source", "device", "nvr", "page", "event")),
                         ("ga4_users_window", ("page",)), ("page_seo_device_daily", ("device",))):
        for kind in kinds:
            lines.extend((
                f"ALTER TABLE analytics.{table} ADD COLUMN {kind}_kind text GENERATED ALWAYS AS ('{kind}'::text) STORED;",
                f"ALTER TABLE analytics.{table} ADD CONSTRAINT {table}_{kind}_fk FOREIGN KEY ({kind}_kind, {kind}_key) "
                "REFERENCES analytics.ga4_value(kind, value_key) DEFERRABLE INITIALLY DEFERRED;",
            ))
    lines.append((HERE / "operations.sql").read_text(encoding="utf-8"))
    (HERE / "schema.sql").write_text("\n\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"Generated {len(TABLES)} extracted tables plus local operation metadata")


if __name__ == "__main__":
    generate()
