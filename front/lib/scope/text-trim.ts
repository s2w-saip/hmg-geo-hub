// JS `String.prototype.trim()` 의 SQL 쌍둥이를 위한 문자 집합.
//
// 배경(2026-08-29 경계 프로브): 표기 접두 규칙과 비경쟁 제외는 JS(result-adapter,
// 프로젝트 표면)와 SQL(scope-aggregates, 표준 표면) 두 경로로 구현돼 있고, 두
// 경로가 갈리면 같은 언급이 화면마다 다른 브랜드로 귀속된다. JS 는 판정 전에
// `.trim()` 을 하는데 SQL 에는 트림이 없어 **선행 공백이 붙은 표기**("  Genesis")
// 에서 JS=Genesis / SQL=미매칭으로 갈렸다(프로브 44건 중 3건. 현 미러 해당 0건
// 이라 잠재 결함이었지만, 미러는 scope NER 출력이라 언제든 유입될 수 있다).
//
// Postgres `btrim(col, chars)` 는 "이 문자들 중 아무거나"를 양끝에서 제거하므로
// 아래 집합을 그대로 넘기면 `.trim()` 과 **정확히 같은 결과**가 된다.
// 기본 `btrim(col)` 은 U+0020 만 제거하고, POSIX `[[:space:]]` 는 U+FEFF 를 공백
// 으로 보지 않는다(둘 다 프로덕션 실측 2026-08-29) — 그래서 명시 집합을 쓴다.
//
// 집합의 정본은 JS 런타임이다. text-trim.test.ts 가 코드포인트 전 구간(0..0x10FFFF)
// 을 훑어 `.trim()` 이 지우는 문자 집합을 재도출해 이 상수와 대조한다 — 엔진이
// 유니코드를 갱신해 집합이 달라지면 그 테스트가 먼저 깨진다.
export const JS_TRIM_CHARS =
  "\u0009\u000a\u000b\u000c\u000d\u0020\u00a0\u1680" +
  "\u2000\u2001\u2002\u2003\u2004\u2005\u2006\u2007\u2008\u2009\u200a" +
  "\u2028\u2029\u202f\u205f\u3000\ufeff";

// **접두 규칙 전용** 선행 트림 — POSIX 정규식 안에서 쓴다.
//
// 왜 btrim 이 아니라 정규식 클래스인가: `^` 앵커 규칙에서 트림이 바꾸는 것은
// **선행** 공백뿐이고(후행 공백은 이미 `([^[:alnum:]]|$)` 경계가 흡수한다),
// 정규식은 어차피 매 행 평가되므로 선행 클래스 하나를 붙이는 비용이 사실상 0이다.
// 프로덕션 EXPLAIN ANALYZE 실측(2026-08-29, AE 브랜드표 쿼리 · 동일 플랜):
//   접두 CASE 원형              1,904 ms
//   btrim(col, JS_TRIM_CHARS)   2,492 ms  (+31%)
//   `^[<ws>]*` 클래스           1,942 ms  (+2%, 노이즈 수준)
// 등가는 유지되고 값만 싸다 — 그래서 접두 경로는 이쪽을 쓴다. 반면 비경쟁 제외의
// `NOT IN` 은 **동등 비교**라 정규식으로 대체할 수 없어 btrim 을 그대로 쓴다
// (같은 실측에서 +79ms/134k행 — 정합을 위해 지불한다).
//
// ⚠️ POSIX bracket expression 안에 그대로 넣으므로 `]`·`^`·`-`·`\` 가 섞이면
// 깨진다. JS_TRIM_CHARS 는 전부 공백류라 안전하고, text-trim.test 가 이를 단언한다.
export const POSIX_LEADING_TRIM = `[${JS_TRIM_CHARS}]*`;

// 표기 경계 문자 클래스 — Postgres POSIX `[[:alnum:]]` 의 JS 쌍둥이.
//
// 프로덕션 실측(2026-08-29): PG 의 `[[:alnum:]]` 은 유니코드 카테고리 L* 와 **Nd**
// 만 참이다. 위첨자·로마숫자·원문자(U+00B2 `²` No · U+2161 `Ⅱ` Nl · U+2460 `①` No ·
// U+00BD `½` No)는 전부 거짓이고, 아랍-인도 숫자(U+0663)·전각 숫자(U+FF11)·한글·
// CJK·악센트 라틴은 참이다. 즉 `[[:alnum:]]` ≡ `[\p{L}\p{Nd}]`.
//
// 종전 JS 쪽은 `\p{N}`(Nd+Nl+No 전부)이라 `"Genesis²"` 에서 SQL=Genesis 매칭 /
// JS=미매칭으로 갈렸다(프로브 44건 중 3건). `\p{Nd}` 로 좁혀 양쪽을 일치시킨다.
// ⚠️ `[[:alnum:]]` 의 판정은 DB 의 ctype 에 달려 있다 — 위 실측은 프로덕션 미러
// 기준이다. DB 로케일을 바꾸면 이 등가를 재확인할 것.
export const NAME_BOUNDARY_CLASS = "\\p{L}\\p{Nd}";
