#!/usr/bin/env node
// Regenerates the backend API contract used by lib/hgh/*:
//
//   1. back/ (FastAPI)  ->  front/lib/hgh/openapi.json   (app.openapi(), sorted keys)
//   2. openapi.json     ->  front/lib/hgh/api-types.ts   (openapi-typescript)
//
// One command, reproducible:
//   node scripts/gen-api-types.mjs              # regenerate both files
//   node scripts/gen-api-types.mjs --types-only # skip step 1 (no Python needed)
//   node scripts/gen-api-types.mjs --check      # regenerate in memory, exit 1 on drift
//
// Python interpreter for step 1: $HGH_BACK_PYTHON, else <repo>/back/.venv/bin/python,
// else python3. It must have the back/ runtime dependencies installed
// (pip install --require-hashes -r back/requirements.lock; back/requirements-dev.lock adds the test tools).
// The OpenAPI document does not read HGH_* settings, so no secrets or DB are needed.
//
// CI (ci/github-workflows/front-ci.yml) runs step 1 + 2 and then `git diff --exit-code`
// so a backend contract change that was not regenerated here fails the build.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const FRONT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ROOT = join(FRONT, "..");
const BACK = join(ROOT, "back");
const OPENAPI_JSON = join(FRONT, "lib/hgh/openapi.json");
const API_TYPES = join(FRONT, "lib/hgh/api-types.ts");

const PY_DUMP =
  "import json; from app.main import app; " +
  "print(json.dumps(app.openapi(), ensure_ascii=False, indent=1, sort_keys=True))";

const HEADER =
  "// Generated by scripts/gen-api-types.mjs from lib/hgh/openapi.json. Do not edit by hand.\n" +
  "// Regenerate: node scripts/gen-api-types.mjs (CI fails on drift).\n" +
  "/* eslint-disable */\n";

const args = new Set(process.argv.slice(2));
const unknown = [...args].filter((a) => a !== "--types-only" && a !== "--check");
if (unknown.length) {
  console.error(`unknown argument(s): ${unknown.join(" ")}`);
  process.exit(2);
}
const typesOnly = args.has("--types-only");
const check = args.has("--check");

function pythonBin() {
  if (process.env.HGH_BACK_PYTHON) return process.env.HGH_BACK_PYTHON;
  const venv = join(BACK, ".venv/bin/python");
  return existsSync(venv) ? venv : "python3";
}

function dumpOpenApi() {
  const py = pythonBin();
  let out;
  try {
    out = execFileSync(py, ["-c", PY_DUMP], {
      cwd: BACK,
      encoding: "utf8",
      maxBuffer: 64 * 1024 * 1024,
      stdio: ["ignore", "pipe", "inherit"],
    });
  } catch {
    console.error(
      `\nOpenAPI export failed with "${py}". It needs the back/ dependencies ` +
        '(pip install --require-hashes -r back/requirements.lock); point HGH_BACK_PYTHON at such an interpreter, ' +
        "or use --types-only to regenerate api-types.ts from the committed openapi.json.",
    );
    process.exit(2);
  }
  const doc = JSON.parse(out); // fail fast on anything that is not JSON
  if (!doc || typeof doc !== "object" || !doc.paths || !doc.components) {
    throw new Error("app.openapi() output has no paths/components");
  }
  return out.endsWith("\n") ? out : `${out}\n`;
}

async function renderTypes(openapiText) {
  const { default: openapiTS, astToString } = await import("openapi-typescript");
  const ast = await openapiTS(JSON.parse(openapiText));
  return HEADER + astToString(ast);
}

const openapiText = typesOnly ? readFileSync(OPENAPI_JSON, "utf8") : dumpOpenApi();
const typesText = await renderTypes(openapiText);

const outputs = [
  [OPENAPI_JSON, openapiText],
  [API_TYPES, typesText],
];

if (check) {
  const drift = outputs.filter(([file, text]) => !existsSync(file) || readFileSync(file, "utf8") !== text);
  for (const [file] of drift) console.error(`drift: ${relative(ROOT, file)}`);
  if (drift.length) {
    console.error("API contract drift. Run: node front/scripts/gen-api-types.mjs");
    process.exit(1);
  }
  console.log("OK: lib/hgh/openapi.json and api-types.ts match the backend.");
} else {
  for (const [file, text] of outputs) {
    if (typesOnly && file === OPENAPI_JSON) continue;
    writeFileSync(file, text);
  }
  const doc = JSON.parse(openapiText);
  const ops = Object.values(doc.paths).reduce((n, item) => n + Object.keys(item).length, 0);
  console.log(
    `OK: ${ops} operations, ${Object.keys(doc.components.schemas ?? {}).length} schemas -> ` +
      `${relative(ROOT, OPENAPI_JSON)}, ${relative(ROOT, API_TYPES)}`,
  );
}
